"""Immutable models for bug-fixing agents and generated candidate patches."""

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


class PersonaType(StrEnum):
    """Specialized repair agent personas."""

    SURGICAL_MINIMALIST = "surgical_minimalist"
    DEFENSIVE_GUARDIAN = "defensive_guardian"
    ARCHITECTURAL_FIXER = "architectural_fixer"
    CONTRACT_ENFORCER = "contract_enforcer"


class AgentPersona(BaseModel):
    """Specification of an agent persona configuration."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    persona_type: PersonaType
    system_prompt: str
    max_tokens: int = Field(default=2048, gt=0)
    temperature: float = Field(default=0.2, ge=0.0, le=1.0)


class CandidatePatch(BaseModel):
    """Represents a patch proposal generated by an agent persona."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    candidate_id: str
    persona: PersonaType
    diff: str
    explanation: str
    lines_added: int = Field(ge=0)
    lines_deleted: int = Field(ge=0)
